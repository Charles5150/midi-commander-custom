#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Generate the Valeton GP-200 template, python/templates/GP-200.csv.

The GP-200 has a fixed MIDI map, the "MIDI Control Information List" of its
manual (firmware V1.7.4), so nothing has to be assigned on it: out of the
box it listens on every channel, Omni, from MIDI IN and USB.

    python3 python/make_gp200_template.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

from lib.templateMaker import NO_SEND, full_range_pedals, global_settings, write_template  # noqa: E402
from make_demo_config import Demo  # noqa: E402

OUT = os.path.join(HERE, "templates", "GP-200.csv")

CHANNEL = "1"           # any channel does while the GP-200 is on Omni
# CC#0 before each Program Change: 1 is patches 01-A to 32-D, 0 the next
# 128, the other way round from what one would think
PATCH_BANK = "1"

# The GP-200's MIDI map; the on / off ones: 0-63 off, 64-127 on
CC_VOLUME = "7"         # Patch Volume, 0-100
CC_EXP = "11"           # EXP 1, 0-100
CC_DST = "49"
CC_AMP = "50"
CC_MOD = "54"
CC_DLY = "55"
CC_RVB = "56"
CC_WAH = "57"
CC_TUNER = "58"
CC_LOOPER = "59"        # the looper on / off
CC_LOOP_REC = "60"
CC_LOOP_AUTO = "61"     # record when the playing starts
CC_LOOP_PLAY = "62"     # 0-63 stop, 64-127 play
CC_LOOP_SPEED = "63"    # 0-63 half speed, 64-127 normal
CC_LOOP_DIR = "64"      # 0-63 reverse, 64-127 normal
CC_LOOP_DELETE = "65"
CC_CTRL = ("69", "70", "71", "72", "76", "77", "78", "79")     # CTRL 1-8
CC_TAP = "75"
PRESS = "127"

PRESET_BANKS = 30       # banks 0-29 load patches 01-A to 08-B
LOOP_BANK = 30
CTRL_BANK = 31


def patch_name(program):
    """The GP-200's own name for a patch: 01-A ... 01-D, 02-A..."""
    return f"{program // 4 + 1:02d}-{'ABCD'[program % 4]}"


def switch(d, bank, btn, label, number):
    d.cc(bank, btn, label, number, toggle="Y", ch=CHANNEL)


def press(d, bank, btn, label, number):
    d.cc(bank, btn, label, number, off=NO_SEND, ch=CHANNEL)


def build():
    d = Demo()
    names = {}

    for bank in range(PRESET_BANKS):
        names[bank] = (patch_name(bank).replace("-", ""), "GP-200")
        d.on_enter(bank, CommandType="PC",
                   **{"Channel_(PC/CC/Note/PB)": CHANNEL, "Number_(PC/CC/Note)": str(bank),
                      "BankSelect_(PC)": str(int(PATCH_BANK) * 128), "BankSelectHighByte_(PC)": "Y"})
        for btn, label, number in (("1", "DST", CC_DST), ("2", "AMP", CC_AMP), ("3", "MOD", CC_MOD),
                                   ("4", "DLY", CC_DLY), ("A", "RVB", CC_RVB), ("B", "WAH", CC_WAH),
                                   ("C", "TUNR", CC_TUNER)):
            switch(d, bank, btn, label, number)
        # Tap sends only on the press; a second message would count as a tap
        press(d, bank, "D", "TAP", CC_TAP)

    names[LOOP_BANK] = ("LOOP", "looper")
    switch(d, LOOP_BANK, "1", "LOOP", CC_LOOPER)
    press(d, LOOP_BANK, "2", "REC", CC_LOOP_REC)
    switch(d, LOOP_BANK, "3", "PLAY", CC_LOOP_PLAY)
    press(d, LOOP_BANK, "4", "AREC", CC_LOOP_AUTO)
    # Lit while half speed, and while reversed
    d.cc(LOOP_BANK, "A", "HALF", CC_LOOP_SPEED, on="0", off=PRESS, toggle="Y", ch=CHANNEL)
    d.cc(LOOP_BANK, "B", "REV", CC_LOOP_DIR, on="0", off=PRESS, toggle="Y", ch=CHANNEL)
    press(d, LOOP_BANK, "C", "DEL", CC_LOOP_DELETE)
    press(d, LOOP_BANK, "D", "TAP", CC_TAP)

    names[CTRL_BANK] = ("CTRL", "CTRL 1-8")
    for btn, number, n in zip(("1", "2", "3", "4", "A", "B", "C", "D"), CC_CTRL, range(1, 9)):
        switch(d, CTRL_BANK, btn, f"CTL{n}", number)

    full_range_pedals(d)
    d.exp.loc[[0, 1], "Out_Max"] = "100"     # EXP 1 and Patch Volume go up to 100
    return d, names


def main() -> int:
    d, names = build()
    return write_template(OUT, d, names, global_settings("GP-200", CHANNEL, CC_EXP, CC_VOLUME),
                          "Valeton GP-200 template, generated by make_gp200_template.py")


if __name__ == "__main__":
    sys.exit(main())
