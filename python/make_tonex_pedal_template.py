#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Generate the IK Multimedia TONEX Pedal template, python/templates/TONEX_Pedal.csv.

The TONEX Pedal has a fixed MIDI map, the MIDI chapter of its user manual
(document 1.6.22), so nothing has to be assigned on it: only its MIDI
channel, MIDI CH in its settings, has to match CHANNEL.

No Bank Select goes before the Program Changes: the pedal starts in its
bank 0, presets 00A to 42B, and its CC#32 is the modulation's on / off.

    python3 python/make_tonex_pedal_template.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

from lib.templateMaker import NO_SEND, full_range_pedals, global_settings, write_template  # noqa: E402
from make_demo_config import Demo  # noqa: E402

OUT = os.path.join(HERE, "templates", "TONEX_Pedal.csv")

CHANNEL = "1"           # the TONEX Pedal's MIDI CH

# The TONEX Pedal's MIDI map; the on / off ones: 0 off, 127 on
CC_DELAY = "2"
CC_TUNER = "9"
CC_TAP = "10"
CC_EXP = "11"           # Expression
CC_PRESET = "12"        # the preset on, or bypassed
CC_GATE = "14"
CC_COMP = "18"
CC_MOD = "32"
CC_REVERB = "75"
CC_PRESET_DOWN = "86"
CC_PRESET_UP = "87"
CC_BANK_DOWN = "89"
CC_BANK_UP = "90"
CC_GAIN = "102"         # the amp's GAIN knob
PRESS = "127"

PRESET_BANKS = 31       # banks 0-30 load presets 00A to 10A, PC 0-30
NAV_BANK = 31


def preset_name(program):
    """The TONEX Pedal's own name for a preset: 00A, 00B, 00C, 01A..."""
    return f"{program // 3:02d}{'ABC'[program % 3]}"


def switch(d, bank, btn, label, number):
    d.cc(bank, btn, label, number, toggle="Y", ch=CHANNEL)


def press(d, bank, btn, label, number):
    d.cc(bank, btn, label, number, off=NO_SEND, ch=CHANNEL)


def tuner_and_tap(d, bank):
    # The tuner opens on one press and closes on the next
    switch(d, bank, "C", "TUNR", CC_TUNER)
    # Tap sends only on the press; a second message would count as a tap
    press(d, bank, "D", "TAP", CC_TAP)


def build():
    d = Demo()
    names = {}

    for bank in range(PRESET_BANKS):
        names[bank] = (preset_name(bank), "TONEX")
        d.on_enter(bank, CommandType="PC",
                   **{"Channel_(PC/CC/Note/PB)": CHANNEL, "Number_(PC/CC/Note)": str(bank)})
        # Lit while the preset is bypassed
        d.cc(bank, "1", "BYP", CC_PRESET, on="0", off=PRESS, toggle="Y", ch=CHANNEL)
        for btn, label, number in (("2", "GATE", CC_GATE), ("3", "COMP", CC_COMP), ("4", "MOD", CC_MOD),
                                   ("A", "DLY", CC_DELAY), ("B", "RVB", CC_REVERB)):
            switch(d, bank, btn, label, number)
        tuner_and_tap(d, bank)

    names[NAV_BANK] = ("NAV", "presets")
    press(d, NAV_BANK, "1", "BNK-", CC_BANK_DOWN)
    press(d, NAV_BANK, "2", "BNK+", CC_BANK_UP)
    press(d, NAV_BANK, "A", "PRS-", CC_PRESET_DOWN)
    press(d, NAV_BANK, "B", "PRS+", CC_PRESET_UP)
    d.cc(NAV_BANK, "3", "BYP", CC_PRESET, on="0", off=PRESS, toggle="Y", ch=CHANNEL)
    tuner_and_tap(d, NAV_BANK)

    full_range_pedals(d)
    return d, names


def main() -> int:
    d, names = build()
    return write_template(OUT, d, names, global_settings("TONEX Pedal", CHANNEL, CC_EXP, CC_GAIN),
                          "IK Multimedia TONEX Pedal template, generated by make_tonex_pedal_template.py")


if __name__ == "__main__":
    sys.exit(main())
