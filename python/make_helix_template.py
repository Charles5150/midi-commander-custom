#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Generate the Line 6 Helix template, python/templates/Helix.csv.

For a Helix Floor or Helix LT: both have the same fixed MIDI map, the "MIDI
CC" table of their owner's manuals (firmware 3.80), so nothing has to be
assigned on them: only the MIDI Base Channel, Global Settings > MIDI/Tempo,
has to match CHANNEL.

    python3 python/make_helix_template.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

from lib.templateMaker import NO_SEND, full_range_pedals, global_settings, write_template  # noqa: E402
from make_demo_config import Demo  # noqa: E402

OUT = os.path.join(HERE, "templates", "Helix.csv")

CHANNEL = "1"           # the Helix's MIDI Base Channel

# The Helix's MIDI map
CC_EXP1 = "1"           # EXP 1 and EXP 2 pedals
CC_EXP2 = "2"
# FS1-FS5 on the top row, FS7-FS11 on the bottom one: FS6 is MODE
CC_FS = {1: "49", 2: "50", 3: "51", 4: "52", 5: "53", 7: "54", 8: "55", 9: "56", 10: "57", 11: "58"}
CC_LOOP_REC = "60"      # 64-127 record, 0-63 overdub
CC_LOOP_PLAY = "61"     # 64-127 play, 0-63 stop
CC_LOOP_ONCE = "62"
CC_LOOP_UNDO = "63"
CC_TAP = "64"
CC_LOOP_REV = "65"      # 64-127 reverse, 0-63 forward
CC_LOOP_HALF = "66"     # 64-127 half speed, 0-63 full speed
CC_TUNER = "68"
CC_SNAPSHOT = "69"      # 0-7 = snapshots 1-8, 8 = next, 9 = previous

PRESET_BANKS = 30       # banks 0-29 load presets 0-29, 01A to 08B
LOOP_BANK = 30
FS_BANK = 31
SNAPSHOT_BUTTONS = ("1", "2", "3", "4", "A", "B")
# The pedal's top row, 1-4, is the Helix's top row, FS1-FS4; the bottom
# row, A-D, its bottom one, FS7-FS10
FS_BUTTONS = (("1", 1), ("2", 2), ("3", 3), ("4", 4), ("A", 7), ("B", 8), ("C", 9), ("D", 10))


def preset_name(program):
    """The Helix's own name for a preset: 01A ... 01D, 02A..."""
    return f"{program // 4 + 1:02d}{'ABCD'[program % 4]}"


def build():
    d = Demo()
    names = {}

    for bank in range(PRESET_BANKS):
        names[bank] = (preset_name(bank), f"prst {bank:03d}")
        d.on_enter(bank, CommandType="PC",
                   **{"Channel_(PC/CC/Note/PB)": CHANNEL, "Number_(PC/CC/Note)": str(bank)})
        for snapshot, btn in enumerate(SNAPSHOT_BUTTONS, 1):
            # An exclusive group, so the LED and the display show the
            # snapshot last picked; switching it off sends nothing
            d.cc(bank, btn, f"SNP{snapshot}", CC_SNAPSHOT, on=str(snapshot - 1), off=NO_SEND,
                 toggle="Y", ch=CHANNEL)
            d.group(bank, btn, 1)
        # The tuner opens on one press and closes on the next
        d.cc(bank, "C", "TUNR", CC_TUNER, toggle="Y", ch=CHANNEL)
        # Tap sends only on the press; a second message on the release would
        # count as another tap
        d.cc(bank, "D", "TAP", CC_TAP, off=NO_SEND, ch=CHANNEL)

    names[LOOP_BANK] = ("LOOP", "looper")
    d.cc(LOOP_BANK, "1", "REC", CC_LOOP_REC, off=NO_SEND, ch=CHANNEL)
    d.cc(LOOP_BANK, "2", "DUB", CC_LOOP_REC, on="0", off=NO_SEND, ch=CHANNEL)
    d.cc(LOOP_BANK, "3", "PLAY", CC_LOOP_PLAY, toggle="Y", ch=CHANNEL)
    d.cc(LOOP_BANK, "4", "HALF", CC_LOOP_HALF, toggle="Y", ch=CHANNEL)
    d.cc(LOOP_BANK, "A", "ONCE", CC_LOOP_ONCE, off=NO_SEND, ch=CHANNEL)
    d.cc(LOOP_BANK, "B", "UNDO", CC_LOOP_UNDO, off=NO_SEND, ch=CHANNEL)
    d.cc(LOOP_BANK, "C", "REV", CC_LOOP_REV, toggle="Y", ch=CHANNEL)
    d.cc(LOOP_BANK, "D", "TAP", CC_TAP, off=NO_SEND, ch=CHANNEL)

    names[FS_BANK] = ("FS", "stomps")
    for btn, fs in FS_BUTTONS:
        # Each message presses the footswitch once, which switches whatever
        # is assigned to it
        d.cc(FS_BANK, btn, f"FS{fs}", CC_FS[fs], toggle="Y", ch=CHANNEL)

    full_range_pedals(d)
    return d, names


def main() -> int:
    d, names = build()
    return write_template(OUT, d, names, global_settings("Helix", CHANNEL, CC_EXP1, CC_EXP2),
                          "Line 6 Helix Floor / LT template, generated by make_helix_template.py")


if __name__ == "__main__":
    sys.exit(main())
