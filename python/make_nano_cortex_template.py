#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Generate the Neural DSP Nano Cortex template, python/templates/Nano_Cortex.csv.

The Nano Cortex has a fixed MIDI map since NanOS 2.1, its manual's incoming
CCs, so nothing has to be assigned on it: its MIDI Channel has to match
CHANNEL, and its EXP/MIDI jack has to be set to MIDI in the app. That jack
is TRS MIDI Type A: the pedal's MIDI OUT reaches it through a DIN to TRS
Type A adapter.

    python3 python/make_nano_cortex_template.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

from lib.templateMaker import NO_SEND, full_range_pedals, global_settings, write_template  # noqa: E402
from make_demo_config import Demo  # noqa: E402

OUT = os.path.join(HERE, "templates", "Nano_Cortex.csv")

CHANNEL = "1"           # the Nano Cortex's MIDI Channel

# The Nano Cortex's MIDI map; the slots: 0-63 off, 64-127 on
CC_EXP = "1"            # the expression position
CC_GATE = "34"
CC_CAPTURE = "35"
CC_CAB = "36"
CC_FX = ("37", "38", "39", "40", "41")     # FX slots 1-5
CC_TAP = "42"           # any value is a tap
CC_TUNER = "43"         # 64-127 opens, 0-63 closes

PRESET_BANKS = 31       # banks 0-30 load presets 1-31, PC 0-30
SLOT_BANK = 31


def slot(d, bank, btn, label, number):
    d.cc(bank, btn, label, number, toggle="Y", ch=CHANNEL)


def build():
    d = Demo()
    names = {}

    for bank in range(PRESET_BANKS):
        names[bank] = (f"P{bank + 1:02d}", "Nano")
        d.on_enter(bank, CommandType="PC",
                   **{"Channel_(PC/CC/Note/PB)": CHANNEL, "Number_(PC/CC/Note)": str(bank)})
        slot(d, bank, "1", "CAPT", CC_CAPTURE)
        for btn, number, n in zip(("2", "3", "4", "A", "B"), CC_FX, range(1, 6)):
            slot(d, bank, btn, f"FX{n}", number)
        # The tuner opens on one press and closes on the next
        slot(d, bank, "C", "TUNR", CC_TUNER)
        # Tap sends only on the press; a second message on the release would
        # count as another tap
        d.cc(bank, "D", "TAP", CC_TAP, off=NO_SEND, ch=CHANNEL)

    names[SLOT_BANK] = ("SLOT", "on / off")
    for btn, label, number in zip(("1", "2", "3", "4", "A", "B", "C", "D"),
                                  ("GATE", "CAPT", "CAB", "FX1", "FX2", "FX3", "FX4", "FX5"),
                                  (CC_GATE, CC_CAPTURE, CC_CAB) + CC_FX):
        slot(d, SLOT_BANK, btn, label, number)

    full_range_pedals(d)
    return d, names


def main() -> int:
    d, names = build()
    # Both pedals move the Nano Cortex's one expression input
    return write_template(OUT, d, names, global_settings("Nano Cortex", CHANNEL, CC_EXP, CC_EXP),
                          "Neural DSP Nano Cortex template, generated by make_nano_cortex_template.py")


if __name__ == "__main__":
    sys.exit(main())
