#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Generate the IK Multimedia TONEX Board template, python/templates/TONEX_Board.csv.

The TONEX Board has a fixed MIDI map, the MIDI chapter of its user manual
(document 1.1.0), so nothing has to be assigned on it: only its MIDI
channel has to match CHANNEL.

    python3 python/make_tonex_board_template.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

from lib.templateMaker import NO_SEND, full_range_pedals, global_settings, write_template  # noqa: E402
from make_demo_config import Demo  # noqa: E402

OUT = os.path.join(HERE, "templates", "TONEX_Board.csv")

CHANNEL = "1"           # the TONEX Board's MIDI channel
SETLIST = "0"           # CC#0 before each Program Change: 0-11 = setlists 01-12

# The TONEX Board's MIDI map
CC_FS = ("35", "36", "37")      # footswitches A-C: 127 is a press
CC_SCENE = "39"         # 0-2 = scenes A-C
CC_TUNER = "41"         # 127 opens, 0 closes
CC_MODE = "43"          # 0 Preset, 1 Scene, 2 Stomp
CC_MODE_STEP = "44"     # 0 the mode before, 127 the next one
CC_TAP = "45"
PRESS = "127"

PRESET_BANKS = 31       # banks 0-30 load presets 01A to 11A of SETLIST
MODE_BANK = 31


def preset_name(program):
    """The TONEX Board's own name for a preset: 01A, 01B, 01C, 02A..."""
    return f"{program // 3 + 1:02d}{'ABC'[program % 3]}"


def footswitch(d, bank, btn, label, number):
    # Each press presses the footswitch, so both presses send one
    d.cc(bank, btn, label, number, on=PRESS, off=PRESS, toggle="Y", ch=CHANNEL)


def build():
    d = Demo()
    names = {}

    for bank in range(PRESET_BANKS):
        names[bank] = (preset_name(bank), "TONEX")
        # CC#0 picks the setlist; the CC#32 that goes with it is no control
        # on the Board
        d.on_enter(bank, CommandType="PC",
                   **{"Channel_(PC/CC/Note/PB)": CHANNEL, "Number_(PC/CC/Note)": str(bank),
                      "BankSelect_(PC)": str(int(SETLIST) * 128), "BankSelectHighByte_(PC)": "Y"})
        for btn, scene in (("1", "A"), ("2", "B"), ("3", "C")):
            # An exclusive group, so the LED and the display show the scene
            # last picked; switching it off sends nothing
            d.cc(bank, btn, f"SCN{scene}", CC_SCENE, on=str("ABC".index(scene)), off=NO_SEND,
                 toggle="Y", ch=CHANNEL)
            d.group(bank, btn, 1)
        # The tuner opens on one press and closes on the next
        d.cc(bank, "4", "TUNR", CC_TUNER, toggle="Y", ch=CHANNEL)
        for btn, number, fs in zip(("A", "B", "C"), CC_FS, "ABC"):
            footswitch(d, bank, btn, f"FS-{fs}", number)
        d.cc(bank, "D", "TAP", CC_TAP, off=NO_SEND, ch=CHANNEL)

    names[MODE_BANK] = ("MODE", "switches")
    for btn, label, value in (("1", "PRST", "0"), ("2", "SCN", "1"), ("3", "STMP", "2")):
        d.cc(MODE_BANK, btn, label, CC_MODE, on=value, off=NO_SEND, toggle="Y", ch=CHANNEL)
        d.group(MODE_BANK, btn, 1)
    d.cc(MODE_BANK, "4", "TUNR", CC_TUNER, toggle="Y", ch=CHANNEL)
    d.cc(MODE_BANK, "A", "MOD-", CC_MODE_STEP, on="0", off=NO_SEND, ch=CHANNEL)
    d.cc(MODE_BANK, "B", "MOD+", CC_MODE_STEP, on=PRESS, off=NO_SEND, ch=CHANNEL)
    d.cc(MODE_BANK, "D", "TAP", CC_TAP, off=NO_SEND, ch=CHANNEL)

    full_range_pedals(d)
    # The Board has no CC for an expression pedal: the pedals set the speed
    # of the pedal's own LFOs instead, and send nothing
    d.exp.loc[[0, 1], "Output"] = "Speed"
    return d, names


def main() -> int:
    d, names = build()
    return write_template(OUT, d, names, global_settings("TONEX Board", CHANNEL, "", ""),
                          "IK Multimedia TONEX Board template, generated by make_tonex_board_template.py")


if __name__ == "__main__":
    sys.exit(main())
